"""Builds the downloadable HotSeat prep sheet: a one-file HTML page (print to PDF) and a Markdown version."""
from __future__ import annotations

import html
from datetime import datetime

from . import engine


def _e(x) -> str:
    return html.escape(str(x or ""))


def build(s: dict) -> tuple[str, str]:
    """s: case, board, pitch, worksheet, transcript, stances, votes, verdict, self, ai, calib, final."""
    date = datetime.now().strftime("%d %b %Y")
    board = {m["id"]: m for m in s["board"]}
    start = s.get("start") or {m["id"]: m["opening_stance"] for m in s["board"]}
    rows = "".join(
        f"<tr><td>{_e(m['avatar'])} <b>{_e(m['name'])}</b><br><span class=m>{_e(m['role'])}</span></td>"
        f"<td>{engine.stance_label(start[m['id']])}</td><td><b>{engine.stance_label(s['stances'][m['id']])}</b></td>"
        f"<td>{_e(s['votes'][m['id']])}</td><td>{_e(m['concern'])}</td></tr>" for m in s["board"])
    exchanges = ""
    for x in s["transcript"]:
        if x["who"] == "Student":
            exchanges += f"<div class='you'><b>You:</b> {_e(x['text'])}</div>"
        else:
            exchanges += f"<div class='q'><b>{_e(x['who'])}:</b> {_e(x['text'])}</div>"
    unresolved = [board[k] for k, v in s["stances"].items() if v <= 0]
    unres = "".join(f"<li><b>{_e(m['name'])} ({_e(m['role'])})</b>: {_e(m['concern'])}. "
                    f"Would need: {_e(m['convinced_by'])}.</li>" for m in unresolved) or "<li>None. Everyone ended positive.</li>"
    grade_rows, ai = "", s.get("ai")
    for r in engine.RUBRIC:
        k = r["id"]
        a = s["final"].get(k, "-") if ai else "-"
        why = _e(ai["scores"][k]["why"]) if ai else ""
        grade_rows += f"<tr><td>{_e(r['name'])}</td><td>{s['self'].get(k, '-')}</td><td><b>{a}</b></td><td>{why}</td></tr>"
    lists = ""
    if ai:
        for title, key in (("What went well", "strengths"), ("Improve next time", "improvements"),
                           ("Questions you should prepare for", "likely_questions")):
            lists += f"<h2>{title}</h2><ul>" + "".join(f"<li>{_e(x)}</li>" for x in ai.get(key, [])) + "</ul>"
    calib = s.get("calib") or {}
    html_doc = f"""<!doctype html><html><head><meta charset="utf-8"><title>Prep sheet: {_e(s['case']['title'])}</title>
<style>
body{{font-family:Georgia,'Times New Roman',serif;max-width:820px;margin:32px auto;padding:0 20px;color:#16181D;line-height:1.5}}
h1{{font-size:26px;margin:0}} h2{{font-size:17px;margin:26px 0 8px;border-bottom:2px solid #E4572E;padding-bottom:4px;font-family:Helvetica,Arial,sans-serif}}
.m{{color:#666;font-size:12px}} .tag{{display:inline-block;background:#16181D;color:#fff;padding:3px 10px;border-radius:4px;font-family:Helvetica,Arial,sans-serif;font-size:13px}}
table{{border-collapse:collapse;width:100%;font-size:13px;font-family:Helvetica,Arial,sans-serif}} td,th{{border-bottom:1px solid #ddd;padding:6px;text-align:left;vertical-align:top}}
.box{{background:#FBF4F1;border-left:4px solid #E4572E;padding:10px 14px;white-space:pre-wrap;font-size:14px}}
.q{{margin:8px 0 2px;color:#444}} .you{{margin:0 0 10px 18px;padding:6px 10px;background:#F3F5F8;border-radius:6px}}
@media print{{body{{margin:0}} h2{{page-break-after:avoid}} .you,.q{{page-break-inside:avoid}}}}
</style></head><body>
<p class=m>HotSeat prep sheet · {date} · Board mood: {_e(s.get('mood', 'Standard'))}</p>
<h1>{_e(s['case']['title'])}</h1>
<p><b>Decision:</b> {_e(s['case']['decision_question'])}</p>
<p><span class=tag>Board verdict: {_e(s['verdict'][0])} ({_e(s['verdict'][1])})</span>
{f"&nbsp;<span class=tag>Grade: {engine.overall(s['final'])}/100</span>" if ai else ""}
{f"&nbsp;<span class=tag>Calibration: {_e(calib.get('label'))}</span>" if ai else ""}</p>
<h2>Your pitch</h2><div class=box>{_e(s['pitch'])}</div>
<h2>Framework worksheet</h2><div class=box>{_e(s['worksheet'] or 'Not filled.')}</div>
<h2>The board</h2><table><tr><th>Member</th><th>Started</th><th>Ended</th><th>Vote</th><th>Main concern</th></tr>{rows}</table>
<h2>Still unresolved</h2><ul>{unres}</ul>
<h2>Self-assessment vs professor</h2><table><tr><th>Criterion</th><th>You</th><th>AI</th><th>Why</th></tr>{grade_rows}</table>
{lists}
<h2>Meeting transcript</h2>{exchanges}
<p class=m>Generated by HotSeat. AI feedback can be wrong; check it against the case.</p>
</body></html>"""

    md = [f"# Prep sheet: {s['case']['title']}", f"*{date}*", "",
          f"**Decision:** {s['case']['decision_question']}",
          f"**Board verdict:** {s['verdict'][0]} ({s['verdict'][1]})"]
    if ai:
        md += [f"**Grade:** {engine.overall(s['final'])}/100 · **Calibration:** {calib.get('label')}"]
    md += ["", "## Your pitch", s["pitch"], "", "## Framework worksheet", s["worksheet"] or "Not filled.", "",
           "## The board", "| Member | Started | Ended | Vote |", "|---|---|---|---|"]
    md += [f"| {m['name']} ({m['role']}) | {engine.stance_label(start[m['id']])} | "
           f"{engine.stance_label(s['stances'][m['id']])} | {s['votes'][m['id']]} |" for m in s["board"]]
    md += ["", "## Still unresolved"] + [f"- **{m['name']}**: {m['concern']}" for m in unresolved] or ["- None"]
    md += ["", "## Self-assessment vs AI", "| Criterion | You | AI |", "|---|---|---|"]
    md += [f"| {r['name']} | {s['self'].get(r['id'], '-')} | {s['final'].get(r['id'], '-') if ai else '-'} |" for r in engine.RUBRIC]
    if ai:
        for title, key in (("What went well", "strengths"), ("Improve next time", "improvements"),
                           ("Questions to prepare for", "likely_questions")):
            md += ["", f"## {title}"] + [f"- {x}" for x in ai.get(key, [])]
    md += ["", "## Transcript"] + [f"**{x['who']}:** {x['text']}  " for x in s["transcript"]]
    return html_doc, "\n".join(md)
